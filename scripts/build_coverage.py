#!/usr/bin/env python3
"""Build inventory/coverage_matrix.md from inventory/sources/*.yaml.

Each cell shows the best access available for that jurisdiction and Quoin section,
counting the jurisdiction's own sources plus state/regional sources that cover it
(entries with no `covers:` list apply to all six). Entries with `in_matrix: false`
(aggregates, non-public, unverified) are excluded.
"""
from pathlib import Path

from pull_samples import ROOT, load_sources

JURISDICTIONS = [
    ("arlington", "Arlington County"),
    ("fairfax_county", "Fairfax County"),
    ("loudoun", "Loudoun County"),
    ("alexandria", "City of Alexandria"),
    ("falls_church", "City of Falls Church"),
    ("fairfax_city", "City of Fairfax"),
]
SECTIONS = [
    "identity", "assessment", "tax", "delinquency_tax_sale", "special_assessment",
    "ownership", "transfer", "deed_reference", "permit", "license",
    "inspection_enforcement", "building", "land",
]
# Lower rank = better access.
RANK = {"bulk": 0, "api": 0, "portal_search": 1, "paid": 2, "request_only": 3}
SYMBOL = {0: "✅", 1: "🔎", 2: "💲", 3: "📨", None: "❌"}
LOCAL = {j for j, _ in JURISDICTIONS}


def applies_to(source):
    if source["jurisdiction"] in LOCAL:
        return {source["jurisdiction"]}
    return set(source.get("covers") or LOCAL)


def main():
    sources = [s for s in load_sources() if s.get("in_matrix", True)]
    best = {}  # (jurisdiction, section) -> (rank, [source_ids])
    for s in sources:
        rank = RANK[s["access_type"]]
        for j in applies_to(s):
            for sec in s["quoin_sections"]:
                cur = best.get((j, sec))
                if cur is None or rank < cur[0]:
                    best[(j, sec)] = (rank, [s["source_id"]])
                elif rank == cur[0]:
                    cur[1].append(s["source_id"])

    lines = [
        "# Coverage matrix",
        "",
        "Generated by `scripts/build_coverage.py` from `inventory/sources/*.yaml`. Do not edit by hand.",
        "",
        "Each cell shows the best public access found for that section.",
        "",
        "| Symbol | Meaning |",
        "|---|---|",
        "| ✅ | Free bulk download or API |",
        "| 🔎 | Searchable one parcel at a time |",
        "| 💲 | Paid or subscription |",
        "| 📨 | By request or FOIA only |",
        "| ❌ | Nothing found |",
        "",
        "Every ✅ API source was sampled successfully on 2026-10-11 (see `samples/`). A few ✅ cells rest on PDFs that need parsing (Loudoun Land Book and Route 28) or on narrow datasets (Alexandria permits are special-use permits only; several license cells are alcohol licenses only). Check the sources listed below each table.",
        "",
        "| Jurisdiction | " + " | ".join(SECTIONS) + " |",
        "|---" * (len(SECTIONS) + 1) + "|",
    ]
    for j, name in JURISDICTIONS:
        cells = [SYMBOL[best.get((j, sec), (None,))[0]] for sec in SECTIONS]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")

    lines += ["", "## Sources behind each cell", ""]
    for j, name in JURISDICTIONS:
        lines.append(f"### {name}")
        lines.append("")
        for sec in SECTIONS:
            rank, ids = best.get((j, sec), (None, []))
            lines.append(f"- **{sec}** {SYMBOL[rank]} " + (", ".join(f"`{i}`" for i in ids) or "none found"))
        lines.append("")

    out = ROOT / "inventory" / "coverage_matrix.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
